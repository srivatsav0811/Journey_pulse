"""
preprocess.py
=============
Turns each raw dataset into the same tidy form:

    events       one row per state visit:   customer, time, state, key
    transitions  one row per a -> b step:   customer, a, b, src_time, batch

Nothing downstream of `load_dataset(name)` knows which dataset it is.

State mapping for REES46 clickstream data (see README "Method"):
  * Each session starts with Visitor (inferred, not logged).
  * view -> Product View, cart -> Add to Cart, remove_from_cart -> Product View.
  * All purchase events in one session are one order.
  * Before a customer's first order they move through the browsing funnel;
    a new session starts at Visitor again.
  * From the first order on, the customer moves through ORDER STAGES:
    order 1 -> Purchase, order 2 -> Repeat Purchase, order >= LOYAL_AT ->
    Loyal Customer. Their browsing between orders is not re-entered into the
    funnel. Re-entering it would create Add to Cart -> Loyal edges that let a
    memoryless chain send a brand-new visitor straight to "Loyal".
  * Exit = churn: appended after the last activity if the customer is then
    inactive for CHURN_DAYS before the data ends; otherwise right-censored.
  * Only transitions whose source event is at least CHURN_DAYS before the
    end of the data are used: for later events the outcome is not yet known.
  * Customers are identified by small integer codes. The raw user_ids are
    19-digit numbers that float64 cannot tell apart, which silently merged
    neighbouring customers in an earlier prototype.
"""

