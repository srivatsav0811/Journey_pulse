// Datasets — which data the model is built from: one comparison table and one card per dataset.
// Every dataset is modelled on its own; they are never pooled into a single matrix.
import { api, state } from "../api.js";
import { h, card } from "../ui.js";
import { pct, money, int, date } from "../format.js";
import { hbars } from "../charts.js";

const ABOUT = {
  electronics: {
    role: "Main dataset",
    text: "Clickstream from a multi-category online electronics store: product views, add-to-cart and purchase events, each with a customer id and a session id. Collected by the REES46 marketing platform. All headline results use this dataset.",
    folder: "data/raw/electronics/", files: "events.csv",
  },
  cosmetics: {
    role: "Generalisation check",
    text: "Clickstream from an online cosmetics shop (views, add-to-cart, remove-from-cart and purchases), also from REES46. A 10% sample of customers is used, keeping each sampled customer's whole history. It tests whether the Electronics conclusions carry over.",
    folder: "data/raw/cosmetics/", files: "five monthly CSVs (2019-Oct … 2020-Feb)",
  },
  synthetic: {
    role: "Drift-detector test",
    text: "Generated by the project team: complete customer journeys in which the Cart → Purchase probability is raised from 0.35 to 0.50 in February. Because the true change is known, it shows whether drift detection finds it. It has no prices, so order value is a fixed 60.",
    folder: "data/synthetic/", files: "synthetic_customer_events.csv (included)",
  },
};

const val = (f, key, fmt = int) => (f && f[key] != null ? fmt(f[key]) : "–");
const period = (f) => (f && f.start ? `${date(f.start)} – ${date(f.end)}` : "–");

export async function render(root) {
  const metas = state.meta.datasets;
  const methods = {};
  await Promise.all(metas.filter((d) => d.available).map(async (d) => {
    methods[d.name] = await api("/api/method", { params: { dataset: d.name } });
  }));
  const factsOf = (name) => (methods[name] ? methods[name].facts : null);
  const real = (name) => { const f = factsOf(name); return f && !f.complete_journeys; };

  // ------------------------------------------------------------------ overview
  const intro = card("Datasets used", "Each dataset is turned into customer journeys and modelled separately. They are never pooled into one matrix.");
  intro.body.append(h("p", { class: "soft" },
    "Two real clickstream datasets from REES46 (via Kaggle) and one synthetic dataset built to test drift detection. ",
    "The raw files are not stored in the repository: you download them from Kaggle and the app turns them into monthly transition counts. ",
    "The dataset currently selected in the sidebar is marked ", h("strong", {}, "In use"), "."));

  // ------------------------------------------------------------------ comparison table
  const cols = metas.map((d) => d.name);
  const wrap = { style: { whiteSpace: "normal" } };
  const row = (label, cell) => h("tr", {}, h("td", wrap, label), ...cols.map((n) => h("td", wrap, factsOf(n) ? cell(factsOf(n), n) : "–")));
  const cmp = card("Side by side", "Counts are after the cleaning and sampling rules described on the Data & method page.");
  cmp.body.append(h("div", { class: "table-wrap" }, h("table", {},
    h("thead", {}, h("tr", {}, h("th", {}, ""), ...metas.map((d) => h("th", {}, d.label.replace("REES46 ", ""))))),
    h("tbody", {},
      row("Role", (f, n) => ABOUT[n].role),
      row("Type", (f, n) => (real(n) ? "Real clickstream" : "Synthetic")),
      row("Period", (f) => period(f)),
      row("Monthly batches", (f, n) => { const b = methods[n].batches; return `${b.length}: ${b[0].label} to ${b[b.length - 1].label}`; }),
      row("Raw rows", (f) => val(f, "rows_raw")),
      row("Customers", (f) => val(f, "customers")),
      row("Sessions", (f) => val(f, "sessions")),
      row("Orders", (f) => val(f, "orders")),
      row("Transitions used", (f) => val(f, "transitions_used")),
      row("Sampling", (f) => (f.sampled ? "10% of customers" : "all data")),
      row("Average order value", (f) => money(f.aov)),
      row("Churn rule", (f, n) => (real(n) ? `${f.churn_days} days inactive` : "built into the data"))))));

  // ------------------------------------------------------------------ one card per dataset
  const cards = metas.map((d) => {
    const f = factsOf(d.name), info = ABOUT[d.name];
    const inUse = d.name === state.dataset;
    const c = card(d.label, info.role, { badge: h("span", { class: inUse ? "status ok" : "status" }, inUse ? "In use" : d.available ? "Available" : "Not downloaded") });
    c.body.append(h("p", { class: "soft" }, info.text));
    if (f) {
      const evTitle = f.complete_journeys ? "State visits" : "Event types";
      const events = Object.entries(f.event_counts).sort((a, b) => b[1] - a[1]).map(([label, v]) => ({ label, values: { n: v } }));
      c.body.append(h("div", {}, h("div", { class: "eyebrow" }, evTitle),
        hbars(events, { series: [{ key: "n", name: evTitle, color: "var(--ink-3)" }], fmt: int, labelWidth: 120 })));
      const dl = h("dl", { class: "facts" });
      const add = (k, v) => dl.append(h("dt", {}, k), h("dd", {}, v));
      if (real(d.name)) {
        add("Cleaning", `${int(f.duplicates_removed)} duplicate rows and ${int(f.null_session_rows_removed)} rows without a session removed`);
        add("Buyers", `${int(f.buyers)} (${int(f.buyers_2plus)} ordered twice, ${int(f.buyers_3plus)} three or more times)`);
        add("Cart abandonment", `${pct(f.cart_abandonment)} of sessions with a cart had no order`);
        add("Only used up to", `${date(f.cutoff)} (later events have no known outcome yet)`);
      } else {
        add("Order value", f.aov_note);
      }
      add("Sampling rule", f.sample_rule);
      add("Source", h("a", { href: /^https?:/.test(f.source) ? f.source : null, target: "_blank", rel: "noopener" }, f.source));
      add("Attribution", f.attribution);
      c.body.append(dl);
    } else {
      c.body.append(h("p", { class: "callout-inline" },
        `Not loaded on this machine. Download it from Kaggle and put the files in ${info.folder} (${info.files}), then restart the server. The README has the steps.`),
        h("p", { class: "small" }, h("a", { href: d.source, target: "_blank", rel: "noopener", style: { textDecoration: "underline" } }, "Open on Kaggle")));
    }
    return c;
  });

  const terms = card("Terms of use", "Please keep this attribution in any report or slides.");
  terms.body.append(h("p", { class: "soft" },
    "The REES46 datasets are published on Kaggle by mkechinov with the licence shown as “Data files © Original Authors”. ",
    "Credit: REES46 Marketing Platform (rees46.com), via Kaggle. Check each dataset's Kaggle page for the current terms before reusing the data."));

  root.append(intro, cmp, h("div", { class: "grid-2" }, ...cards.slice(0, 2)), cards[2] || null, terms);
}
